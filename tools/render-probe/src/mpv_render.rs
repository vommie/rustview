//! mpv's render context on Slint's OpenGL context.
//!
//! libmpv2's `RenderContext` borrows the `Mpv` it was created from; `self_cell` keeps both in one struct, so the context is
//! always freed before its handle (mpv: "You must free the context with mpv_render_context_free() before the mpv core is
//! destroyed"). It must be created and dropped while the GL context is current: the surface does both in Slint's notifier.
#![allow(unsafe_code, reason = "bridges Slint's GL loader into libmpv's C callback")]

use std::ffi::{CStr, CString, c_void};
use std::sync::Arc;

use libmpv2::Mpv;
use libmpv2::render::{OpenGLInitParams, RenderParam, RenderParamApiType, mpv_render_update};

/// The self-referential pair, generated by `self_cell` (kept in its own module so the lint exception covers only that code).
mod cell {
    #![allow(
        clippy::mem_forget,
        reason = "self_cell's generated constructor forgets its drop guard on success, by design"
    )]

    use std::sync::Arc;

    use libmpv2::Mpv;
    use libmpv2::render::RenderContext;

    self_cell::self_cell!(
        /// The mpv handle and the render context that borrows it.
        pub struct MpvRender {
            owner: Arc<Mpv>,
            #[covariant]
            dependent: RenderContext,
        }
    );
}

pub use cell::MpvRender;

/// Slint's GL loader, reachable from the plain `fn` libmpv2 wants: the address of a `&dyn Fn` that lives on the stack of
/// [`MpvRender::create`] while `mpv_render_context_create` runs. mpv resolves every GL function inside that call
/// (`video/out/opengl/libmpv_gl.c`, `mpgl_load_functions2` in `init`) and libmpv2 frees this value right after it.
struct ProcLoader(*const c_void);

type Loader<'a> = &'a dyn Fn(&CStr) -> *const c_void;

fn resolve(loader: &ProcLoader, name: &str) -> *mut c_void {
    let Ok(name) = CString::new(name) else {
        return std::ptr::null_mut();
    };
    // SAFETY: `loader.0` is the address of the `Loader` local in `MpvRender::create`, which is alive for the whole
    // `create_render_context` call, the only time mpv calls this function (see `ProcLoader`). It is only read.
    let get_proc_address: &Loader<'_> = unsafe { &*loader.0.cast::<Loader<'_>>() };
    get_proc_address(&name).cast_mut()
}

impl MpvRender {
    /// Creates mpv's OpenGL renderer on the current context.
    pub fn create(mpv: Arc<Mpv>, get_proc_address: Loader<'_>) -> Result<Self, libmpv2::Error> {
        let loader: Loader<'_> = get_proc_address;
        let proc_loader = ProcLoader((&raw const loader).cast());
        Self::try_new(mpv, |mpv| {
            mpv.create_render_context(vec![
                RenderParam::ApiType(RenderParamApiType::OpenGl),
                RenderParam::InitParams(OpenGLInitParams {
                    get_proc_address: resolve,
                    ctx: proc_loader,
                }),
            ])
        })
    }

    /// Calls `callback` (on one of mpv's threads) whenever a new frame should be drawn. It must not call mpv.
    pub fn set_update_callback(&mut self, callback: impl Fn() + Send + 'static) {
        self.with_dependent_mut(|_, ctx| ctx.set_update_callback(callback));
    }

    /// Whether mpv has a new frame to draw (must be called after each update callback).
    pub fn has_new_frame(&self) -> bool {
        match self.borrow_dependent().update() {
            Ok(flags) => flags & mpv_render_update::Frame != 0,
            Err(e) => {
                eprintln!("mpv render update failed: {e}");
                false
            }
        }
    }

    /// Draws the current frame into framebuffer `fbo` of `width` x `height` pixels, top row first (not flipped).
    pub fn render(&self, fbo: i32, width: i32, height: i32) -> Result<(), libmpv2::Error> {
        self.borrow_dependent().render::<ProcLoader>(fbo, width, height, false)
    }

    /// Tells mpv that a frame was presented (helps its timing; called after every Slint frame).
    pub fn report_swap(&self) {
        self.borrow_dependent().report_swap();
    }
}
